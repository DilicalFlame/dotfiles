-- Terminals (logic in features/terminal.lua).
local map = vim.keymap.set
local opts = { noremap = true, silent = true }
local term = require("features.terminal")
-- ── Terminals ───────────────────────────────────────────────────────────────
map("t", "<C-]>", "<C-\\><C-n>", opts)
map("n", "<leader>tt", function()
  term.toggle("root")
end, { desc = "Terminal below (project root)" })
map("n", "<leader>tT", function()
  term.toggle("root", true)
end, { desc = "Terminal right (project root)" })
map("n", "<leader>tc", function()
  term.toggle("file")
end, { desc = "Terminal below (file dir)" })
map("n", "<leader>tC", function()
  term.toggle("file", true)
end, { desc = "Terminal right (file dir)" })
map("n", "<leader>tn", term.new, { desc = "New terminal (next free number)" })
map("n", "<leader>tl", term.pick, { desc = "List terminals" })
map("n", "<leader>t]", function()
  term.cycle(1)
end, { desc = "Next terminal" })
map("n", "<leader>t[", function()
  term.cycle(-1)
end, { desc = "Previous terminal" })
-- also from inside a terminal (no need to leave terminal mode). Needs the WezTerm bindings in wezterm.lua.
map({ "n", "t" }, "<C-.>", function()
  term.cycle(1)
end, { desc = "Next terminal" })
map({ "n", "t" }, "<C-,>", function()
  term.cycle(-1)
end, { desc = "Previous terminal" })
map("n", "<leader>fw", function()
  term.wezterm_tab(vim.fn.getcwd())
end, { desc = "WezTerm tab (cwd)" })
map("n", "<leader>fW", function()
  term.wezterm_tab(term.buf_dir())
end, { desc = "WezTerm tab (file dir)" })
-- hide the terminal you are in, otherwise bring back the last one still alive (never makes a new one if any exist)
map({ "n", "t" }, "<c-/>", term.toggle_last, { desc = "Terminal (toggle last)" })
map({ "n", "t" }, "<c-_>", term.toggle_last, { desc = "which_key_ignore" })
